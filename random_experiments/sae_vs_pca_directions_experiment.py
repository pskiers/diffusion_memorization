# --- 3. HELPER: SDXL DIRECTION EXTRACTOR ---
class SDXLDirectionExtractor:
    def __init__(self, model_id=MODEL_ID, device=DEVICE):
        print(f"Loading SDXL Text Encoders from {model_id}...")
        self.pipe = StableDiffusionXLPipeline.from_pretrained(
            model_id, torch_dtype=torch.float16, variant="fp16", use_safetensors=True
        ).to(device)
        self.device = device

    def get_token_embedding(self, prompt, target_word):
        """
        Extracts the concatenated hidden states (Text Encoder 1 + 2)
        for the specific token index corresponding to 'target_word'.
        """
        # 1. Tokenize to find the index of the target word
        # SDXL has two tokenizers. We need to find the word index in both.
        # Note: This simple logic assumes the target word is a single token.

        def get_idx(tokenizer, prompt, word):
            tokens = tokenizer.encode(prompt)
            decoded = [tokenizer.decode([t]).strip().lower() for t in tokens]
            word = word.lower()
            try:
                # Find index. Note: prompt often starts with <start> token (idx 0)
                return decoded.index(word)
            except ValueError:
                # Fallback: try finding subword
                for i, d in enumerate(decoded):
                    if word in d:
                        return i
                print(f"Warning: Word '{word}' not found in prompt '{prompt}' tokens: {decoded}")
                return -1

        idx1 = get_idx(self.pipe.tokenizer, prompt, target_word)
        idx2 = get_idx(self.pipe.tokenizer_2, prompt, target_word)

        # 2. Run Encoders
        with torch.no_grad():
            # Encoder 1
            txt_input1 = self.pipe.tokenizer(prompt, return_tensors="pt", padding="max_length", max_length=77).to(
                self.device
            )
            out1 = self.pipe.text_encoder(txt_input1.input_ids, output_hidden_states=True)
            # Last hidden state: (Batch, Seq, 768)
            emb1 = out1.last_hidden_state[0, idx1]  # Shape (768,)

            # Encoder 2
            txt_input2 = self.pipe.tokenizer_2(prompt, return_tensors="pt", padding="max_length", max_length=77).to(
                self.device
            )
            out2 = self.pipe.text_encoder_2(txt_input2.input_ids, output_hidden_states=True)
            # Last hidden state: (Batch, Seq, 1280)
            emb2 = out2.last_hidden_state[0, idx2]  # Shape (1280,)

        # 3. Concatenate (Standard SDXL conditioning is concat of both)
        # Shape: (2048,)
        return torch.cat([emb1, emb2], dim=0).float().cpu().numpy()

    def get_semantic_direction(self, concept, attribute):
        """
        Direction = Embed(Attribute + Concept) - Embed(Concept)
        We align by extracting the 'concept' token from both strings.
        """
        base_prompt = f"a photo of a {concept}"
        attr_prompt = f"a photo of a {attribute} {concept}"

        # We extract the specific token vector for "{concept}" from both sentences
        # to minimize positional noise, though "context" will bleed in via self-attention.
        vec_base = self.get_token_embedding(base_prompt, concept)
        vec_attr = self.get_token_embedding(attr_prompt, concept)

        direction = vec_attr - vec_base
        # Normalize direction
        return direction / np.linalg.norm(direction)


# --- 4. METRICS: GINI & CORRELATION ---
def gini_coefficient(x):
    """
    Calculate the Gini coefficient of a numpy array.
    x: array of non-negative numbers (absolute correlations).
    Returns: Gini index [0, 1]. Higher = More unequal (Sparser/Better).
    """
    x = np.abs(x) + 1e-10  # Ensure positive
    sorted_x = np.sort(x)
    n = len(x)
    cumx = np.cumsum(sorted_x, dtype=float)
    # The formula for the Gini coefficient
    return (n + 1 - 2 * np.sum(cumx) / cumx[-1]) / n


def compute_correlations(direction, basis):
    """
    Computes Cosine Similarity between 'direction' (D,) and every vector in 'basis' (D, K).
    Returns: (K,) array of absolute correlations.
    """
    # Normalize basis columns just in case
    basis_norm = basis / (np.linalg.norm(basis, axis=0, keepdims=True) + 1e-9)
    dir_norm = direction / (np.linalg.norm(direction) + 1e-9)

    # Dot product (Cosine sim since normalized)
    correlations = np.dot(dir_norm, basis_norm)
    return np.abs(correlations)


def load_pca_basis(folder_path, max_vecs=30000, threshold_factor=2.5, n=None):
    """Loads gradients and computes PCA basis."""
    files = glob.glob(os.path.join(folder_path, "*.npy"))
    data_list = []
    if not files:
        print(f"  [PCA] No files found in {folder_path}. Generating dummy data.")
        return np.random.randn(2048, 100)  # Mock

    for f in files[: min(len(files), 100)]:  # Limit load for speed in demo
        try:
            arr = np.load(f)
            if arr.ndim == 1:
                arr = arr.reshape(1, -1)
            data_list.append(arr)
        except:
            pass

    X = np.concatenate(data_list, axis=0)
    if len(X) > max_vecs:
        X = X[np.random.choice(len(X), max_vecs, replace=False)]

    # PCA
    pca = GPUPCA()
    pca.fit(X)
    dim = X.shape[1]

    # Thresholding
    threshold = threshold_factor / dim
    sig_indices = np.where(pca.explained_variance_ratio_.cpu().numpy() > threshold)[0]

    if n is not None:
        return pca.components_[:n].T.cpu().numpy()  # Fallback
    # if len(sig_indices) == 0:
    # return pca.components_[:1700].T.cpu().numpy() # Fallback

    return pca.components_[sig_indices].T.cpu().numpy()


