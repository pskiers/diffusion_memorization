def main():
    # A. Init SDXL Extractor
    extractor = SDXLDirectionExtractor()

    results = []

    # B. Iterate Concepts
    for concept, attributes in CONCEPTS.items():
        print(f"\n=== Processing Concept: {concept.upper()} ===")

        paths = DATA_PATHS.get(concept)
        if not paths:
            continue
        pca_path, sae_path = paths

        # 1. Load Subspaces
        print(f"  Loading SAE from {sae_path}...")
        basis_sae = load_sae_directions(sae_path, add_bias=False, low=-6).T
        print(f"    SAE Shape: {basis_sae.shape}")

        print(f"  Loading PCA from {pca_path}...")
        basis_pca = load_pca_basis(pca_path, n=basis_sae.shape[1])
        print(f"    PCA Shape: {basis_pca.shape}")

        # 2. Iterate Attributes
        for attr in attributes:
            print(f"  > Extracting direction for '{attr}'...")

            # Get semantic direction from SDXL
            sem_dir = extractor.get_semantic_direction(concept, attr)

            # Compare with PCA
            corr_pca = compute_correlations(sem_dir, basis_pca)
            gini_pca = gini_coefficient(corr_pca)
            max_corr_pca = np.max(corr_pca)

            # Compare with SAE
            corr_sae = compute_correlations(sem_dir, basis_sae)
            gini_sae = gini_coefficient(corr_sae)
            max_corr_sae = np.max(corr_sae)

            results.append(
                {
                    "Concept": concept,
                    "Attribute": attr,
                    "Label": f"{attr} ({concept})",
                    "PCA Gini": gini_pca,
                    "SAE Gini": gini_sae,
                    "PCA Max Corr": max_corr_pca,
                    "SAE Max Corr": max_corr_sae,
                    "Diff_Max": max_corr_sae - max_corr_pca,
                    "Diff_Gini": gini_sae - gini_pca,
                }
            )

    # --- 6. VISUALIZATION ---
    df = pd.DataFrame(results)

    # --- 4. FILTERING & SORTING LOGIC ---

